/**
 * PROTOTYPE: emits the named-weight tokens from `tokens/weights.mjs` into `dist/prototype/`.
 *
 * Two stylesheets, as `build-tokens.mjs` writes for today's tokens: the web one in `oklch()`, and
 * the native one in hex and `rgba()` with its dark set under `prefers-color-scheme`, the only form
 * react-native-css reads. Both carry the `fg-` utility. And `token-weights.ts`, the same values with
 * their contrast checks as TypeScript data, which `stories/token-weights.stories.tsx` renders —
 * as `cubeui-theme.ts` is today's palette for a TypeScript importer. Nothing here touches the real
 * token build.
 *
 * Run with `--check` to verify the committed output is current without writing. `tokens:build` and
 * `tokens:check` run it after `build-tokens.mjs`, because `token-weights.test.mjs` reads what it
 * writes: a stale file there is a test passing on a palette that has since changed.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { radius } from "../tokens/palette.mjs";
import { OKABE_ITO } from "../tokens/series.mjs";
import {
  derived,
  FILLS,
  HEAVY,
  MEANINGS,
  names,
  SURFACE_STEP,
  tokenNames,
  WEIGHTS,
} from "../tokens/weights.mjs";
import { formatOklch, isOutOfGamut, toNativeCss } from "./oklch.mjs";
import { nestedCardChoice, pairs, series, states } from "./weights-contrast.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist", "prototype");
const check = process.argv.includes("--check");

const block = (selector, map, format, indent = "") =>
  [
    `${indent}${selector} {`,
    ...names.map((n) => `${indent}  --${n}: ${format(map[n])};`),
    `${indent}}`,
  ].join("\n");

const themeInline = [
  "@theme inline {",
  `  --radius-lg: ${radius};`,
  ...names.map((n) => `  --color-${n}: var(--${n});`),
  "}",
].join("\n");

/**
 * Text and icon colour, as one prefix that reads as the partner of `bg-`. It sets `color`, which
 * an icon follows on the web (`currentColor`) and through `IconClassContext` on device.
 */
const FG_UTILITY = ["@utility fg-* {", "  color: --value(--color-*);", "}"].join("\n");

const { default: base, ...others } = derived;

const paletteBlocks = (format, wrap = (s) => s) =>
  Object.entries(others)
    .flatMap(([name, modes]) => {
      const attr = `[data-palette="${name}"]`;
      const both = Boolean(modes.light && modes.dark);
      return [
        modes.light && block(wrap(`html${attr}`), modes.light, format),
        modes.dark && block(wrap(`html${both ? ".dark" : ""}${attr}`), modes.dark, format),
      ];
    })
    .filter(Boolean)
    .join("\n\n");

const HEADER =
  "/* Generated by scripts/build-token-weights.mjs from tokens/weights.mjs. Prototype. */";

const WEB = `${HEADER}

${block(":root", base.light, formatOklch)}

${block(".dark", base.dark, formatOklch)}

${paletteBlocks(formatOklch)}

${themeInline}

${FG_UTILITY}
`;

const NATIVE = `${HEADER}

${block(":root", base.light, toNativeCss)}

@media (prefers-color-scheme: dark) {
${block(":root", base.dark, toNativeCss, "  ")}
}

${block(":is(html.dark)", base.dark, toNativeCss)}

${block(":is(html.light)", base.light, toNativeCss)}

${paletteBlocks(toNativeCss, (s) => `:is(${s})`)}

${themeInline}

${FG_UTILITY}
`;

const TITLES = { default: "Default", monokai: "Monokai" };

/** The values and their checks as data, for the story to render. */
const DATA = `${HEADER}

/** One mode of one palette: every token as the colour React Native draws, and its checks. */
export type TokenWeightsPalette = {
  id: string;
  title: string;
  /** How far a nested card moves from a card, away from the page (\`SURFACE_STEP\`). */
  surfaceStep: number;
  tokens: Record<string, string>;
  checks: { label: string; on: string; ratio: number; floor: number }[];
};

export const tokenNames = ${JSON.stringify(tokenNames)} as const;
export const meanings = ${JSON.stringify(Object.keys(MEANINGS))} as const;
export const fills = ${JSON.stringify(FILLS)} as const;
/** What each chart colour started as, in Okabe and Ito's set. */
export const seriesSources = ${JSON.stringify(OKABE_ITO.map((c) => c.name))} as const;
export const rules = ${JSON.stringify({ weights: WEIGHTS, heavy: HEAVY, surfaceStep: SURFACE_STEP })} as const;

export const palettes: TokenWeightsPalette[] = ${JSON.stringify(
  Object.entries(derived).flatMap(([palette, modes]) =>
    Object.entries(modes).map(([mode, map]) => ({
      id: `${palette}-${mode}`,
      title: `${TITLES[palette] ?? palette} ${mode}`,
      surfaceStep: (SURFACE_STEP[palette] ?? SURFACE_STEP.default)[mode] ?? 0,
      tokens: Object.fromEntries(tokenNames.map((n) => [n, toNativeCss(map[n])])),
      checks: [...pairs(map).map(({ exact, ...check }) => check), ...states(map), ...series(map)],
    })),
  ),
  null,
  2,
)};

/** The dark-mode choice (#504): a nested card lighter than a card, by each palette's step. */
export const nestedCardChoice = ${JSON.stringify(
  nestedCardChoice().map(({ card, nested, ...row }) => ({
    ...row,
    card: toNativeCss(card),
    nested: toNativeCss(nested),
  })),
  null,
  2,
)};
`;

const files = { "tokens.css": WEB, "tokens.native.css": NATIVE, "token-weights.ts": DATA };

// A clipped colour is silently wrong on device; say so here rather than ship it. Only the colours
// this file computes: a copy of a palette colour (`negative`, and its weights) is already reported
// by `build-tokens.mjs`.
const computed = (n) => n.endsWith("-heavy") || n === "surface-3";
const clipped = Object.entries(derived).flatMap(([palette, modes]) =>
  Object.entries(modes).flatMap(([mode, map]) =>
    names.filter((n) => computed(n) && isOutOfGamut(map[n])).map((n) => `${palette} ${mode} ${n}`),
  ),
);
if (clipped.length > 0) {
  console.warn(`Out of sRGB gamut, clamped: ${clipped.join(", ")}`);
}

let stale = 0;
for (const [file, content] of Object.entries(files)) {
  const path = join(out, file);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      console.error(`dist/prototype/${file} is out of date; run npm run tokens:build`);
      stale++;
    }
  } else {
    mkdirSync(out, { recursive: true });
    writeFileSync(path, content);
  }
}
if (stale > 0) {
  process.exit(1);
}
if (!check) {
  console.log(`Wrote ${Object.keys(files).length} files, ${names.length} tokens per palette.`);
}
